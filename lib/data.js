// Deterministic market-wise prices so server/client always agree.
export function buildMarketPrices(product) {
  const base = product.price;
  return MARKETS.map(([market, area], i) => {
    const seed = (product.id * 31 + i * 17) % 21; // 0..20
    const wobble = (seed - 10) / 100; // -10% .. +10%
    const price = Math.max(1, Math.round(base * (1 + wobble)));
    const spread = Math.max(1, Math.round(price * (0.03 + ((seed % 5) / 100))));
    return { market, area, min: Math.max(1, price - spread), max: price + spread, price };
  });
}
